// 연도 문자열 → [시작, 끝]. "현재"는 +9999로 둔다.
function parseYears(s) {
  if (s.includes("현재")) return [1981, 9999];
  if (s.includes("s")) {
    const a = s.split("-");
    return [+a[0], +a[1].replace("s", "")];
  }
  const [a, b] = s.split("-");
  return [+a, b === undefined ? +a : +b];
}
