/* ---------- 9. 진행 ---------- */
function choose(i) {
  const c = act().ch[i];
  S.lastChoice.push(c.t);
  applyDelta(c.d);
  const [y0, y1] = actSpan();
  const r = riskFor(y0, y1);
  const kids = Math.min(5, Math.floor(Math.random() * 4.4));
  S.banner = { p: r.hazard, events: r.events, kids };
  drawResult(c);
}

function deathCause(r) {
  if (r.events.length) {
    const tot = r.events.reduce((a, e) => a + e.take, 0);
    let x = Math.random() * tot, acc = 0;
    for (const e of r.events) { acc += e.take; if (x <= acc) return e.ev; }
  }
  return null;
}

function childName() {
  const pool = S.roster;
  return pool[Math.floor(Math.random() * pool.length)];
}

function advance() {
  const [y0, y1] = actSpan();
  const r = riskFor(y0, y1);
  const died = Math.random() < r.hazard;
  const ev = deathCause(r);
  const kids = S.banner ? S.banner.kids : Math.min(5, Math.floor(Math.random() * 4.4));

  if (!died) {
    S.gen = genAt(y1);
    S.deepest = Math.max(S.deepest, S.gen);
    S.me.health = clamp(S.me.health - 6 + Math.random() * 10);
    S.me.wealth = clamp(S.me.wealth + (Math.random() * 10 - 3));
    S.banner = null;
    S.ai++;
    if (S.ai >= 7) { S.ai = 0; S.ei++; }
    if (S.ei >= ERAS.length) { S.ei = ERAS.length - 1; drawEnd(); return; }
    drawAct();
    return;
  }

  // 사망
  S.deaths++;
  const type = ev ? ev.type : "other";
  S.ledger[type]++;
  const hasChild = kids > 0;
  const child = hasChild ? childName() : null;

  let title, meta, text, ledger;
  if (ev) {
    title = ev.name;
    meta = `${ev.years} · ${n(ev.deathsMin)}–${n(ev.deathsMax)}명 추정${ev.note ? " · " + ev.note : ""}`;
    ledger = `이 사건으로 인류에서 ${n(ev.deathsMin)}~${n(ev.deathsMax)}명이 죽었다고 추정된다. ` +
             `이 무리의 ${S.ei + 1}번째 시대, ${S.ai + 1}번째 막에서 당신 이름은 멈췄다.`;
    const copy = {
      war: "가장 가까운 집을 태워야 했다. 도망칠 방향이 아니라 갈 곳을 고르는 데서 하루가 다 걸렸다.",
      disease: "열이 오르고, 숨이 차고, 숨은 옆 사람에게 넘어갔다. 이게 병이라는 걸 아는 사람은 이 시대에 없었다.",
      famine: "마지막 밥을 나눴다. 밥이 없어도 나누는 무리만은 이 무리의 마지막 장벽이었다.",
    };
    text = copy[ev.type] + (S.civ.tech > 55 ? " 이 무리는 어느 정도 대비책을 알고 있었다. 그래도 죽었다." :
      S.civ.sci > 55 ? " 원인을 추측한 흔적은 남았다. 맞았는지 틀렸는지는 세기에 이르러도 몰랐다." :
      S.civ.uni > 55 ? " 함께 버틴 무리가 있었다. 그래서 죽은 쪽의 수가 평소보다 적었다." : "");
  } else {
    title = "그 외의 세월";
    meta = `${yearLabel(y0)} — ${yearLabel(y1)}`;
    ledger = "3대 사망원 어느 것도 아니었다. 전염병도, 기근도, 전쟁도 아니었다. 그저 세월이 사람을 가져갔다. 가장 많은 죽음이 늘 이 종류였다.";
    text = "별다른 사건 없이 죽었다. 이 무리에서 대부분의 사람은 이렇게 죽는다. 기록에 남지 않는 죽음이 수만 년 동안 인류의 대부분이었다.";
  }

  drawDeath({ kind: ev ? "event" : "other", title, meta, text, ledger, child });
  S.banner = null;
  S.pendingChild = child;
}

function afterDeath() {
  const child = S.pendingChild;
  S.pendingChild = null;
  const [y0, y1] = actSpan();
  if (child) {
    S.you = child;
    S.me = { health: 65, wealth: Math.max(0, S.me.wealth - 20), fame: Math.max(0, S.me.fame - 15) };
  } else {
    S.lineages++;
    S.me = { health: 65, wealth: 5, fame: 0 };
    S.you = S.roster[Math.floor(Math.random() * 5000)];
  }
  S.gen = genAt(y1);
  S.deepest = Math.max(S.deepest, S.gen);
  S.ai++;
  if (S.ai >= 7) { S.ai = 0; S.ei++; }
  if (S.ei >= ERAS.length) { S.ei = ERAS.length - 1; drawEnd(); return; }
  drawAct();
}
window.afterDeath = afterDeath;

