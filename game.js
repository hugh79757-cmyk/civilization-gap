// 근대 이후만 세계 인구를 썼다. 그 이전은 "이 혈통이 사는 지역의 인구"로 읽는다.
const POP_CURVE = [
  [-70000, 0.5], [-45000, 0.7], [-20000, 0.9], [-12000, 4], [-5000, 14],
  [-3300, 25], [-1200, 90], [-500, 180], [0, 190], [500, 190], [1000, 265],
  [1300, 390], [1500, 425], [1600, 555], [1700, 610], [1800, 900],
  [1850, 1200], [1900, 1250], [1914, 1750], [1939, 2300], [1950, 2500],
  [1980, 4400], [2000, 6100], [2026, 8100],
];
function popAt(year) {
  if (year <= POP_CURVE[0][0]) return POP_CURVE[0][1];
  for (let i = 1; i < POP_CURVE.length; i++) {
    const [x1, y1] = POP_CURVE[i];
    if (year <= x1) {
      const [x0, y0] = POP_CURVE[i - 1];
      return y0 + (y1 - y0) * ((year - x0) / (x1 - x0));
    }
  }
  return POP_CURVE[POP_CURVE.length - 1][1];
}

const GEN_YEARS = 20;              // 세대당 20년 → 70,000년 ≈ 3,500세대
