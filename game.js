/* ---------- 7. 사망 계산 ---------- */
const TYPE_N = { war: "전쟁", disease: "질병", famine: "기근", other: "그 외의 세월" };

function civFactor(type) {
  if (type === "disease") return Math.max(0.12, 1 - 0.60 * S.civ.sci / 100);
  if (type === "famine")  return Math.max(0.20, 1 - 0.50 * S.civ.unity / 100);
  if (type === "war")     return 1 + 0.80 * S.civ.war / 100;
  return 1;
}

/* 한 막(막 구간) 동안 이 혈통이 겪는 위험. {frac, events:[{ev, take}]} */
function riskFor(from, to) {
  let hazard = Math.max(0.02, 0.13 - 0.05 * S.civ.tech / 100);
  const events = [];
  for (const ev of MORTALITY_EVENTS) {
    const evSpan = Math.max(1, ev.to - ev.from);   // "1943" 처럼 1년짜리는 구간 1년으로
    // 연도는 닫힌 구간 [from, to] 로 본다 → 1년짜리 사건도 구간 안이면 걸린다
    const ov = Math.min(to, ev.to + 1) - Math.max(from, ev.from);
    if (ov <= 0) continue;
    const share = ((ov / evSpan) * (ev.deathsMin + Math.random() * (ev.deathsMax - ev.deathsMin)))
      / (popAt(Math.max(from, ev.from)) * 1e6);
    events.push({ ev, take: Math.min(0.92, share * civFactor(ev.type)) });
  }
  for (const e of events) hazard += e.take;
  hazard *= 1 + 0.004 * Math.max(0, S.me.wealth - 40);   // 부의가 시선을 끈다
  hazard *= 1 - 0.28 * S.me.fame / 100;                 // 이름난 사람은 지켜본다
  hazard *= 1 - 0.22 * S.me.health / 100;
  return { hazard: clamp(hazard, 0, 0.97), events, base: Math.max(0, hazard - events.reduce((a, b) => a + b.take, 0)) };
}

